 ctx.save();ctx.translate(x,y);ctx.imageSmoothingEnabled=false;
 const pale={'#a29577':'#b5ac94','#b9ad8c':'#cdc5af','#d0c3a1':'#dfd7c2','#e5d9b8':'#eee8d9','#f0e6cb':'#f7f3e8','#e8ddc0':'#f1ebdd','#ad9b78':'#bdb099','#dfd0ac':'#eae1cd','#ede0bd':'#f4eddf','#eee0bc':'#f2e9d7','#baa480':'#c8b99e','#c9b893':'#d9ccb5','#bead8d':'#d0c3ac'};
